import { readFileSync, writeFileSync } from 'node:fs'
import ts from 'typescript'

for (const directory of ['window', 'terminal']) {
  const preload = new URL(`../../electron/runtime/${directory}/preload`, import.meta.url)
  const source = readFileSync(new URL(`${preload.href}.ts`), 'utf8')
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2023,
      verbatimModuleSyntax: false,
    },
  })
  const script = outputText
    .replace('"use strict";\n', '')
    .replace('Object.defineProperty(exports, "__esModule", { value: true });\n', '')
  writeFileSync(
    new URL(`${preload.href}.cjs`),
    `// Code generated by app/tooling/commands/emit-preload.ts. DO NOT EDIT.\n${script}`,
  )
}
