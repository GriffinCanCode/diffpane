import { writeFile } from 'node:fs/promises'
import { colorPairs, cssRole } from '../../shared/appearance/palette.ts'
import { typography } from '../../shared/appearance/typography.ts'

export const themeTokensPath = new URL('../../renderer/shell/workspace/theme-tokens.css', import.meta.url)

export function renderThemeTokens() {
  const colors = Object.entries(colorPairs).map(([role, [light, dark]]) => [
    cssRole(role),
    `light-dark(${light}, ${dark})`,
  ])
  const declarations = [...colors, ...Object.entries(typography)].map(([property, value]) => `  ${property}: ${value};`)
  return ['/* Generated by node app/tooling/appearance/theme-css.ts */', ':root {', ...declarations, '}', ''].join('\n')
}

if (import.meta.main) await writeFile(themeTokensPath, renderThemeTokens())
